def ler_relatorio():
    r = {}
    for l in RELATORIO.read_text(encoding='utf-8').splitlines():
        c = l.split('\t')
        if len(c) >= 5:
            q = c[2].replace('.', '').replace(',', '.')
            r[c[0]] = {'qtd': float(q) if q else None, 'desc': c[4].strip()}
    return r

